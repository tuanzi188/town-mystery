/* ============================================================
   结案判定（evaluateCase）
   说明：纯函数，供未来「提交证据」UI 调用，按玩家提交线索的角色组合返回 verdict。
   规则：
     core === 0                          → "insufficient"（缺铁证，案件悬置）
     red  >= 1                           → "flawed"      （有干扰，误判风险）
     red  === 0 && aux === 0 && core > 0 → "perfect"     （仅铁证，铁案）
     其他（core + aux，无 red）           → "standard"    （铁证+旁证，标准结案）
   @param levelId       "L1".."L11"
   @param submittedCids 玩家提交的线索 id 数组
   @returns { verdict: string, counts: { core, aux, red, amb } }
   ============================================================ */
function evaluateCase(levelId, submittedCids) {
  var roles = TOWN_CLUE_ROLES[levelId];
  if (!roles) return { verdict: "insufficient", counts: { core: 0, aux: 0, red: 0, amb: 0 } };
  var counts = { core: 0, aux: 0, red: 0, amb: 0 };
  var roleNames = ["core", "aux", "red", "amb"];
  (submittedCids || []).forEach(function (cid) {
    for (var i = 0; i < roleNames.length; i++) {
      if (roles[roleNames[i]].indexOf(cid) !== -1) { counts[roleNames[i]]++; break; }
    }
  });
  var verdict;
  if (counts.core === 0) verdict = "insufficient";
  else if (counts.red >= 1) verdict = "flawed";
  else if (counts.aux === 0) verdict = "perfect";
  else verdict = "standard";
  return { verdict: verdict, counts: counts };
}